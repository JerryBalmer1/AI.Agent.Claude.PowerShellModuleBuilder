<#
    Compare.Tests.ps1 - the acceptance test for the graph comparator.

    WHAT THIS TESTS. The comparator, not the fixture. Given expected-graph.json
    and a candidate graph, Compare-Graph.ps1 must report every difference, and
    must report none when the graphs agree. Nothing here claims the fixture is
    right or that expected-graph.json is a correct oracle; those are separate
    claims and this file cannot speak to either.

    The wrong graphs in assertion 2 are GENERATED by Mutate-Graph.ps1 from
    expected-graph.json, never authored by hand. A hand-written wrong graph
    tests whether the comparator agrees with the person who wrote it; a
    generated one tests whether it detects the specific failure the case
    declares in cases.md.

    Mutations are written under scratch/, which is gitignored, and are never
    committed. expected-graph.json is never modified: every mutation reads it
    and writes elsewhere, and assertion 1 re-reads it afterwards.

    Helpers are dot-sourced from FixtureCase.ps1 because a top-level `function`
    in a Pester 6.1.0 test file breaks every BeforeAll in that file, with a
    misleading loop-label error.

    No network. This suite makes no Azure DevOps call and needs no PAT.
#>

BeforeDiscovery {
    . (Join-Path $PSScriptRoot 'FixtureCase.ps1')

    $script:CasesPathDisc = Join-Path $PSScriptRoot 'fixture/cases.md'
    $DeclaredCases = @(Get-FixtureCaseDeclaration -Path $script:CasesPathDisc |
        ForEach-Object { @{ CaseId = $_.Id; Kind = $_.Kind } })

    # The three difference kinds assertion 4 requires to be distinguishable.
    $EdgeDifferenceKinds = @(
        @{ Probe = 'missing'; ExpectedKind = 'missingEdge' }
        @{ Probe = 'extra';   ExpectedKind = 'extraEdge' }
        @{ Probe = 'target';  ExpectedKind = 'wrongEdgeTarget' }
    )
}

Describe 'Graph comparator' {

    BeforeAll {
        $script:FunctionalRoot = $PSScriptRoot
        $script:ExpectedPath   = Join-Path $PSScriptRoot 'fixture/expected-graph.json'
        $script:ComparePath    = Join-Path $PSScriptRoot 'Compare-Graph.ps1'
        $script:MutatePath     = Join-Path $PSScriptRoot 'Mutate-Graph.ps1'

        $repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..' '..')).ProviderPath
        $script:ScratchRoot = Join-Path $repoRoot 'scratch/0014-compare'
        if (-not (Test-Path $script:ScratchRoot)) {
            New-Item -ItemType Directory -Path $script:ScratchRoot -Force | Out-Null
        }

        # Byte-level guard: expected-graph.json must be unchanged by anything
        # this suite does. Captured here, re-checked in the last assertion.
        $script:ExpectedHashAtStart = (Get-FileHash -LiteralPath $script:ExpectedPath -Algorithm SHA256).Hash

        # Runs the comparator and returns its parsed JSON report plus exit code.
        # A scriptblock rather than a function: see the file header.
        $script:RunCompare = {
            param([string]$Candidate, [string]$Tag)

            $reportPath = Join-Path $script:ScratchRoot "report-$Tag.json"
            if (Test-Path $reportPath) { Remove-Item $reportPath -Force }

            & pwsh -NoProfile -File $script:ComparePath `
                -ExpectedPath $script:ExpectedPath `
                -CandidatePath $Candidate `
                -ReportPath $reportPath `
                -Quiet | Out-Null
            $exit = $LASTEXITCODE

            $report = $null
            if (Test-Path $reportPath) {
                $report = Get-Content -LiteralPath $reportPath -Raw | ConvertFrom-Json
            }
            [pscustomobject]@{ ExitCode = $exit; Report = $report; ReportPath = $reportPath }
        }

        # Generates the wrong graph for a case and returns its path.
        $script:MakeMutant = {
            param([string]$CaseId)

            $out = Join-Path $script:ScratchRoot "mutant-$CaseId.json"
            if (Test-Path $out) { Remove-Item $out -Force }
            & pwsh -NoProfile -File $script:MutatePath `
                -CaseId $CaseId `
                -ExpectedPath $script:ExpectedPath `
                -OutputPath $out | Out-Null
            $out
        }
    }

    Context 'Assertion 1: a graph compared against itself reports zero differences' {

        It 'the comparator script exists' {
            Test-Path -LiteralPath $script:ComparePath |
                Should -BeTrue -Because 'Compare-Graph.ps1 is the subject of this suite'
        }

        It 'expected-graph.json compared with itself reports zero differences and exits 0' {
            $r = & $script:RunCompare $script:ExpectedPath 'self'
            $r.Report | Should -Not -BeNullOrEmpty -Because 'the comparator must write a JSON report'
            $r.Report.differenceCount | Should -Be 0 -Because 'a graph cannot differ from itself'
            $r.Report.agree | Should -BeTrue
            $r.ExitCode | Should -Be 0 -Because 'agreement exits 0'
        }

        It 'a copy of the expected graph also reports zero differences' {
            # Guards against the comparator short-circuiting on identical paths
            # rather than actually comparing content.
            $copy = Join-Path $script:ScratchRoot 'expected-copy.json'
            Copy-Item -LiteralPath $script:ExpectedPath -Destination $copy -Force
            $r = & $script:RunCompare $copy 'copy'
            $r.Report.differenceCount | Should -Be 0
            $r.ExitCode | Should -Be 0
        }
    }

    Context 'Assertion 2: each case has a wrong graph that is detected and named' {

        It 'the mutator script exists' {
            Test-Path -LiteralPath $script:MutatePath |
                Should -BeTrue -Because 'wrong graphs are generated, never hand-authored'
        }

        It '<CaseId> has a generated wrong graph that differs and is named in the report' -ForEach $DeclaredCases {
            $caseId = $CaseId

            $mutant = & $script:MakeMutant $caseId
            Test-Path -LiteralPath $mutant |
                Should -BeTrue -Because "Mutate-Graph.ps1 must emit a wrong graph for $caseId"

            # The mutation must actually have changed something, or this
            # assertion passes on a comparator that reports nothing.
            (Get-FileHash -LiteralPath $mutant -Algorithm SHA256).Hash |
                Should -Not -Be $script:ExpectedHashAtStart -Because "the mutation for $caseId must change the graph"

            $r = & $script:RunCompare $mutant $caseId
            $r.Report | Should -Not -BeNullOrEmpty
            $r.Report.differenceCount |
                Should -BeGreaterThan 0 -Because "the wrong graph for $caseId must be reported as differing"
            $r.ExitCode | Should -Be 1 -Because 'disagreement exits non-zero'
            @($r.Report.cases) |
                Should -Contain $caseId -Because "the report must name $caseId, not merely say the graphs differ"
        }
    }

    Context 'Assertion 3: the comparator is order-insensitive' {

        It 'shuffling nodes and edges changes nothing' {
            $g = Get-Content -LiteralPath $script:ExpectedPath -Raw | ConvertFrom-Json
            $rand = [Random]::new(1404)
            $g.nodes = @($g.nodes | Sort-Object { $rand.Next() })
            $g.edges = @($g.edges | Sort-Object { $rand.Next() })

            $shuffled = Join-Path $script:ScratchRoot 'shuffled.json'
            ($g | ConvertTo-Json -Depth 20) | Set-Content -LiteralPath $shuffled -Encoding utf8NoBOM

            # The shuffle must have actually reordered something.
            $orig = Get-Content -LiteralPath $script:ExpectedPath -Raw | ConvertFrom-Json
            (@($g.nodes | ForEach-Object { $_.id }) -join ',') |
                Should -Not -Be (@($orig.nodes | ForEach-Object { $_.id }) -join ',') -Because 'the shuffle must reorder nodes'

            $r = & $script:RunCompare $shuffled 'shuffled'
            $r.Report.differenceCount |
                Should -Be 0 -Because 'nodes and edges are sets, not sequences'
            $r.ExitCode | Should -Be 0
        }
    }

    Context 'Assertion 4: missing, extra and wrong-target edges are distinguishable' {

        BeforeAll {
            # Three candidates, each differing from expected by exactly one edge
            # change of one kind.
            $script:EdgeProbePaths = @{}

            # missing: drop one template edge
            $g1 = Get-Content -LiteralPath $script:ExpectedPath -Raw | ConvertFrom-Json
            $victim = $g1.edges | Where-Object {
                $_.from -eq 'yaml:pipelines-main/pipelines/p06.yml' -and $_.kind -eq 'template'
            } | Select-Object -First 1
            $g1.edges = @($g1.edges | Where-Object { -not ($_.from -eq $victim.from -and $_.to -eq $victim.to -and $_.kind -eq $victim.kind) })
            $p1 = Join-Path $script:ScratchRoot 'edge-missing.json'
            ($g1 | ConvertTo-Json -Depth 20) | Set-Content -LiteralPath $p1 -Encoding utf8NoBOM
            $script:EdgeProbePaths['missing'] = $p1

            # extra: add an edge between two nodes that already exist
            $g2 = Get-Content -LiteralPath $script:ExpectedPath -Raw | ConvertFrom-Json
            $g2.edges = @($g2.edges) + @([pscustomobject]@{
                from = 'yaml:pipelines-main/pipelines/p10.yml'
                to   = 'yaml:pipelines-main/pipelines/templates/vars-common.yml'
                kind = 'template'
                ref  = 'templates/vars-common.yml'
            })
            $p2 = Join-Path $script:ScratchRoot 'edge-extra.json'
            ($g2 | ConvertTo-Json -Depth 20) | Set-Content -LiteralPath $p2 -Encoding utf8NoBOM
            $script:EdgeProbePaths['extra'] = $p2

            # target: keep from/kind/ref, change only `to`, to another real node
            $g3 = Get-Content -LiteralPath $script:ExpectedPath -Raw | ConvertFrom-Json
            foreach ($e in $g3.edges) {
                if ($e.from -eq 'yaml:pipelines-main/pipelines/p01.yml' -and $e.kind -eq 'template') {
                    $e.to = 'yaml:pipelines-main/templates/steps-build.yml'
                }
            }
            $p3 = Join-Path $script:ScratchRoot 'edge-target.json'
            ($g3 | ConvertTo-Json -Depth 20) | Set-Content -LiteralPath $p3 -Encoding utf8NoBOM
            $script:EdgeProbePaths['target'] = $p3
        }

        It 'a <Probe> edge is reported as <ExpectedKind>' -ForEach $EdgeDifferenceKinds {
            $probe = $Probe
            $wanted = $ExpectedKind

            $r = & $script:RunCompare $script:EdgeProbePaths[$probe] "edge-$probe"
            $r.Report.differenceCount | Should -BeGreaterThan 0

            $kinds = @($r.Report.differences | ForEach-Object { $_.kind } | Sort-Object -Unique)
            $kinds | Should -Contain $wanted -Because "a $probe edge must be reported as '$wanted', not merely as a difference"
        }

        It 'a wrong edge target is not reported as a missing-plus-extra pair' {
            # The point of the assertion. If the comparator keys edges on
            # (from,to,kind) it will call a repointed edge one missing edge and
            # one extra edge, which is true but useless: a wrong resolution
            # target is the failure cases 01 and 04 exist to catch, and it has
            # to be nameable on its own.
            $r = & $script:RunCompare $script:EdgeProbePaths['target'] 'edge-target-precision'
            $kinds = @($r.Report.differences | ForEach-Object { $_.kind })
            $kinds | Should -Contain 'wrongEdgeTarget'
            $kinds | Should -Not -Contain 'missingEdge' -Because 'the edge is present, its target is wrong'
            $kinds | Should -Not -Contain 'extraEdge'   -Because 'no edge was added'
        }

        It 'the wrong-target report names both the expected and the actual target' {
            $r = & $script:RunCompare $script:EdgeProbePaths['target'] 'edge-target-detail'
            $d = @($r.Report.differences | Where-Object { $_.kind -eq 'wrongEdgeTarget' })[0]
            $d.expectedTo | Should -Be 'yaml:pipelines-main/pipelines/templates/steps-build.yml'
            $d.actualTo   | Should -Be 'yaml:pipelines-main/templates/steps-build.yml'
        }
    }

    Context 'Assertion 5: comparison is on graph content only' {

        It 'the report declares its exclusion list' {
            $r = & $script:RunCompare $script:ExpectedPath 'exclusions'
            @($r.Report.excluded).Count |
                Should -BeGreaterThan 0 -Because 'the exclusion list must be explicit, not implied'
            foreach ($x in @($r.Report.excluded)) {
                $x.field  | Should -Not -BeNullOrEmpty
                $x.reason | Should -Not -BeNullOrEmpty -Because 'each exclusion carries a one-line reason'
            }
        }

        It 'the exclusion list names cases, note and generatedBy' {
            $r = & $script:RunCompare $script:ExpectedPath 'exclusions-named'
            $fields = @($r.Report.excluded | ForEach-Object { $_.field })
            $fields | Should -Contain 'cases'
            $fields | Should -Contain 'note'
            $fields | Should -Contain 'generatedBy'
        }

        It 'adding a cases tag to the candidate changes nothing' {
            # The scope control. Tags are an oracle annotation; a module has
            # never read cases.md and cannot produce them, so a candidate that
            # invents one must not be penalised - and one that omits them must
            # not be either.
            $g = Get-Content -LiteralPath $script:ExpectedPath -Raw | ConvertFrom-Json
            $g.nodes[0] | Add-Member -NotePropertyName cases -NotePropertyValue @('case-99') -Force
            $g.edges[0] | Add-Member -NotePropertyName cases -NotePropertyValue @('case-98') -Force
            $tagged = Join-Path $script:ScratchRoot 'tagged.json'
            ($g | ConvertTo-Json -Depth 20) | Set-Content -LiteralPath $tagged -Encoding utf8NoBOM

            $r = & $script:RunCompare $tagged 'tagged'
            $r.Report.differenceCount |
                Should -Be 0 -Because 'cases tags are excluded from comparison'
            $r.ExitCode | Should -Be 0
        }

        It 'adding generatedBy to the candidate changes nothing' {
            $g = Get-Content -LiteralPath $script:ExpectedPath -Raw | ConvertFrom-Json
            $g | Add-Member -NotePropertyName generatedBy -NotePropertyValue 'Get-PipelineGraph 1.0.0' -Force
            $gen = Join-Path $script:ScratchRoot 'generatedby.json'
            ($g | ConvertTo-Json -Depth 20) | Set-Content -LiteralPath $gen -Encoding utf8NoBOM

            $r = & $script:RunCompare $gen 'generatedby'
            $r.Report.differenceCount |
                Should -Be 0 -Because 'the oracle has no generatedBy by design; a run graph does'
            $r.ExitCode | Should -Be 0
        }

        It 'adding a note changes nothing' {
            $g = Get-Content -LiteralPath $script:ExpectedPath -Raw | ConvertFrom-Json
            $g.nodes[0] | Add-Member -NotePropertyName note -NotePropertyValue 'a human annotation' -Force
            $noted = Join-Path $script:ScratchRoot 'noted.json'
            ($g | ConvertTo-Json -Depth 20) | Set-Content -LiteralPath $noted -Encoding utf8NoBOM

            $r = & $script:RunCompare $noted 'noted'
            $r.Report.differenceCount | Should -Be 0
        }
    }

    Context 'The comparator never modifies its inputs' {

        It 'expected-graph.json is byte-identical after every comparison above' {
            (Get-FileHash -LiteralPath $script:ExpectedPath -Algorithm SHA256).Hash |
                Should -Be $script:ExpectedHashAtStart -Because 'the oracle is never modified, by this pass or any comparison'
        }
    }
}
